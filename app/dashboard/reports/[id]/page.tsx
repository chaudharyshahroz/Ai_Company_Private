import * as React from "react";
import { notFound } from "next/navigation";
import { GlassCard } from "@/components/ui/GlassCard";
import { GlowButton } from "@/components/ui/GlowButton";
import { getCurrentUser, listBoardReports } from "@/lib/data";
import { formatDate } from "@/lib/format";
import { CheckCircle2, AlertCircle, Sparkles, TrendingUp, Download } from "lucide-react";

interface Params {
  params: { id: string };
}

export default async function ReportDetailPage({ params }: Params) {
  const user = await getCurrentUser();
  const reports = await listBoardReports(user.id);
  const report = reports.find((r) => r.id === params.id);
  if (!report) notFound();

  const agents = Object.entries(report.agentPerformance);

  return (
    <div className="mx-auto max-w-3xl space-y-8">
      <div>
        <div className="text-xs uppercase tracking-wider text-text-tertiary">
          Weekly board report
        </div>
        <h1 className="mt-2 font-display text-3xl font-bold tracking-tight md:text-4xl">
          {formatDate(report.weekStart)} – {formatDate(report.weekEnd)}
        </h1>
        <div className="mt-3 flex items-center gap-2 text-xs text-text-tertiary">
          <Sparkles size={12} className="text-primary-light" />
          <span>Generated by your CEO Agent · {formatDate(report.createdAt)}</span>
        </div>
      </div>

      {/* KPIs */}
      <div className="grid grid-cols-2 gap-3 md:grid-cols-4">
        <Kpi label="Tasks done" value={report.tasksCompleted} color="text-accent" />
        <Kpi label="Tasks failed" value={report.tasksFailed} color="text-accent-warm" />
        <Kpi label="Top outputs" value={report.topOutputs.length} color="text-primary-light" />
        <Kpi label="Agents active" value={agents.length} color="text-text-primary" />
      </div>

      {/* Executive summary */}
      <GlassCard className="p-7">
        <h2 className="mb-3 flex items-center gap-2 text-base font-semibold text-text-primary">
          <Sparkles size={14} className="text-primary-light" />
          Executive summary
        </h2>
        <p className="text-sm leading-relaxed text-text-secondary">{report.summary}</p>
      </GlassCard>

      {/* Agent performance */}
      <GlassCard className="p-7">
        <h2 className="mb-4 flex items-center gap-2 text-base font-semibold text-text-primary">
          <TrendingUp size={14} className="text-accent" />
          Agent performance
        </h2>
        <div className="space-y-3">
          {agents.map(([name, stats]) => (
            <div key={name} className="flex items-center justify-between text-sm">
              <span className="text-text-primary">{name}</span>
              <div className="flex items-center gap-4 text-xs">
                <span className="text-text-secondary">
                  {stats.completed} done
                </span>
                <span className="text-text-tertiary">
                  {(stats.avgDurationMs / 1000).toFixed(1)}s avg
                </span>
              </div>
            </div>
          ))}
        </div>
      </GlassCard>

      {/* Recommendations */}
      <GlassCard className="p-7">
        <h2 className="mb-4 flex items-center gap-2 text-base font-semibold text-text-primary">
          <Sparkles size={14} className="text-accent" />
          Recommendations for next week
        </h2>
        <ul className="space-y-3">
          {report.recommendations.map((rec, i) => (
            <li key={i} className="flex items-start gap-3 text-sm leading-relaxed text-text-primary">
              <span className="mt-1 inline-flex h-5 w-5 shrink-0 items-center justify-center rounded-full bg-primary/15 text-[10px] font-bold text-primary-light">
                {i + 1}
              </span>
              {rec}
            </li>
          ))}
        </ul>
      </GlassCard>

      <div className="flex justify-center">
        <GlowButton size="sm" variant="secondary">
          <Download size={13} />
          Download PDF
        </GlowButton>
      </div>
    </div>
  );
}

function Kpi({ label, value, color }: { label: string; value: number; color: string }) {
  return (
    <div className="rounded-xl border border-border bg-surface/60 p-4">
      <div className={`text-2xl font-bold tabular-nums ${color}`}>{value}</div>
      <div className="mt-0.5 text-[10px] uppercase tracking-wider text-text-tertiary">{label}</div>
    </div>
  );
}